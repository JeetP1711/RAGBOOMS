/**
 * Generates supabase/seed.sql from src/data/seed.ts.
 *   npm run seed:sql
 * The output is idempotent: re-running it in Supabase never overwrites edits
 * made from the admin panel (every insert is ON CONFLICT DO NOTHING).
 */
import fs from 'node:fs'
import path from 'node:path'
import { seedContent as s } from '../src/data/seed'

const JSONB = new Set(['gallery', 'changelog', 'github_meta', 'value', 'details'])
const q = (v: unknown, col = ''): string => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (typeof v === 'number') return String(v)
  if (JSONB.has(col)) return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`
  if (Array.isArray(v) && v.every((x) => typeof x === 'string'))
    return v.length ? `array[${v.map((x) => q(x)).join(', ')}]::text[]` : `'{}'::text[]`
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`
  return `'${String(v).replace(/'/g, "''")}'`
}

const insert = (table: string, rows: Record<string, unknown>[], conflict = '') => {
  if (!rows.length) return ''
  const cols = Object.keys(rows[0])
  const values = rows.map((r) => `  (${cols.map((c) => q(r[c], c)).join(', ')})`).join(',\n')
  return `insert into public.${table} (${cols.join(', ')}) values\n${values}\non conflict ${conflict}do nothing;\n`
}
const strip = <T extends Record<string, unknown>>(row: T, ...keys: string[]) => {
  const copy: Record<string, unknown> = { ...row }
  for (const k of keys) delete copy[k]
  return copy
}

const catId = new Map(s.categories.map((c) => [c.slug, c.id]))
const techId = new Map(s.technologies.map((t) => [t.name, t.id]))

const catMap: Record<string, unknown>[] = []
const techMap: Record<string, unknown>[] = []
for (const p of s.projects) {
  for (const slug of p.categories) {
    const id = catId.get(slug)
    if (!id) throw new Error(`Unknown category "${slug}" on ${p.title}`)
    catMap.push({ project_id: p.id, category_id: id })
  }
  for (const name of p.technologies) {
    const id = techId.get(name)
    if (!id) throw new Error(`Unknown technology "${name}" on ${p.title} — add it to seed.ts`)
    techMap.push({ project_id: p.id, technology_id: id })
  }
}

const sql = [
  '-- Generated by `npm run seed:sql` from src/data/seed.ts. Do not edit by hand.',
  '-- Run after supabase/migrations/0001_init.sql. Safe to re-run: existing rows are kept.',
  '',
  insert('profiles', [s.profile as unknown as Record<string, unknown>]),
  insert(
    'site_settings',
    Object.entries(s.settings).map(([key, value]) => ({ key, value: value as object })),
  ),
  insert('project_categories', s.categories as never),
  insert('technologies', s.technologies as never),
  insert(
    'projects',
    s.projects.map((p) => strip(p as never, 'categories', 'technologies')),
  ),
  insert('project_category_map', catMap),
  insert('project_technologies', techMap),
  insert('experiences', s.experiences as never),
  insert('achievements', s.achievements as never),
  insert('education', s.education as never),
  insert('social_links', s.socials as never),
].join('\n')

const out = path.resolve(process.cwd(), 'supabase/seed.sql')
fs.writeFileSync(out, sql)
console.log(`Wrote ${out} (${s.projects.length} projects, ${s.technologies.length} technologies)`)
